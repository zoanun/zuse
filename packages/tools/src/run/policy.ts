/**
 * run 的策略参数。
 *
 * v4 §1 的核心论证是「**两档的差异全部落在策略参数上，机制只有一套**」——
 * 片段档（用户点代码块的「运行」）和项目档（在项目目录里跑长命令）共用同一张注册表、
 * 同一个状态机，只是这里的字段取值不同。所以这个类型**不许长出 `kind: 'snippet' | 'project'`
 * 这种判别字段** —— 一旦有了，状态机里就会开始出现 `if (kind === …)`，两档的机制又分叉了。
 */
export interface RunPolicy {
  /** 墙钟上限；null = 不限（项目档）。片段档 300s。 */
  wallClockMs: number | null
  /**
   * 空闲上限；null = 不限。
   *
   * **两档目前都是 null**，各自的理由不同，写在下面两个常量上 ——
   * 这里刻意**不复述取值**：曾经写着「项目档 30 分钟」，而 `PROJECT_POLICY` 早已实测改成
   * null，同一个文件里两段注释互相矛盾。字段注释是 IDE 悬停时看到的那份，
   * 下一个人加第三档策略会照着它抄一个 30 分钟出来，把 `PROJECT_POLICY` 那段记录的事故
   *（没人访问的 dev server 吃完午饭回来被杀）原样请回来。
   *
   * **规矩**：具体数值只在定义它的常量处写一次，别处引用符号名，不复述数字。
   */
  idleMs: number | null
  /** 发出终止信号后等多久升级/放弃。见 run.ts 的 kill 兑现流程。 */
  killGraceMs: number
  /** 订阅者全走光时怎么办。片段档 kill（没人看了就没必要跑），项目档 keep（可重连）。 */
  onDetach: 'kill' | 'keep'
  /**
   * 输出汇。truncate = 满了杀进程；ring = 丢最旧的、进程不动。
   * 预算是**每条流各自**的，不是两条流共享 —— 一个刷屏的 stderr 不该把 stdout 的额度吃光，
   * 那会让「进程报了个警告」表现成「看不到正常输出」。
   */
  sink: { kind: 'truncate'; budget: number } | { kind: 'ring'; chars: number }
}

/**
 * 片段档：用户点了代码块的「运行」。
 *
 * 有墙钟、无空闲计时（墙钟已经兜住了）、没人看就杀、输出超预算就杀。
 * 300s 与 200_000 字符都是可注入的 —— 测试必须能传 200ms 那一档，
 * 否则「墙钟到点被杀」这条按字面写就是一个 5 分钟的测试（spec §7.1）。
 */
export const SNIPPET_POLICY: RunPolicy = {
  wallClockMs: 300_000,
  idleMs: null,
  killGraceMs: 3_000,
  onDetach: 'kill',
  sink: { kind: 'truncate', budget: 200_000 },
}

/**
 * 项目档：在项目目录里跑长命令（dev server、构建）。
 *
 * 无墙钟、**无空闲超时**、断连保留可重连、环形缓冲不杀。
 *
 * ## `idleMs` 为什么是 null（原来是 30 分钟，实测改的）
 *
 * v4 §3 定的是「空闲超时默认开」，那条判据对**片段**成立：一段跑着不吐字的脚本
 * 多半是死循环。但对 dev server 完全相反 —— **不吐字节正是它的正常状态**。实测：
 *
 * ```
 * pnpm -F @zuse/web dev：25 秒内 9 次输出，最后一次在 1085ms，之后安静 23915ms
 * ```
 *
 * 启动完 1 秒就彻底安静。配上「每次输出重置 idle 定时器」，30 分钟的空闲超时意味着
 * **一个没人访问的 dev server 会被自动杀掉**，而 UI 文案是「一直没有输出，已停止」——
 * 用户吃完午饭回来看到这句，完全不知道发生了什么。
 *
 * **代价（写下来，不留白）**：真卡死的项目命令不会被自动收，得用户自己点停止。
 * 可以接受 —— 项目档本来就是「用户盯着的长跑」，右栏一直有停止按钮。
 *
 * 这里原先还有一句「而片段档那边 `idleMs` 仍然开着，误判风险高的是那一侧」——
 * **那是假的**：`SNIPPET_POLICY.idleMs` 也是 null（见上面那个常量），片段档靠的是 300s 墙钟。
 * 也就是说本档取舍的论证曾经建立在同一个文件里一个不成立的前提上。留着这段自我更正，
 * 是因为下一个人最可能的动作恰恰是「片段档都有空闲超时，项目档凭什么没有」——
 * 前提根本不存在。**两档都没有空闲超时，`EndReason` 的 `'idle'` 在生产路径不可达。**
 *
 * **本步（步骤 2）不接线** —— 片段档用不上它。放在这里是因为 v4 §1 的论证要求
 * 两档共用一套机制；只做一档的话，状态机会按 truncate 档的形状长出来，
 * 步骤 4 接项目档时又要改。
 */
export const PROJECT_POLICY: RunPolicy = {
  wallClockMs: null,
  idleMs: null,
  killGraceMs: 3_000,
  onDetach: 'keep',
  sink: { kind: 'ring', chars: 400_000 },
}
